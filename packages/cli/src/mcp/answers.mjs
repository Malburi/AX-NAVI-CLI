/*
 * 빈 답일 때 모델에게 돌려줄 말. 왜 비었는지에 따라 다르다.
 *
 * 무응답을 "확인된 결정"으로 굳히지 못하게 한다. 예전 문구는 "무엇을 가정했는지 밝혀라"까지만
 * 말했다. 모델은 실제로 밝혔지만 그 가정을 파일에 **사용자 확인 내용**으로 적었고, 그 파일이
 * 다음 실행의 스킵 조건이 됐다. 실측으로 이런 기록이 남았다.
 *
 *   ## 사용자 확인 내용
 *   - 초기화 구성: 단일 (AskUserQuestion 무응답 → 기본값 적용)
 *   - source: reused
 *
 * 그래서 일주일 뒤 실행은 "이미 확인됨"으로 보고 다시 묻지 않았다. 한 번의 무응답이 되돌릴 수
 * 없는 결정이 되면 안 된다.
 *
 * 그리고 **답할 사람이 없는 실행**에서는 기본값으로 넘어가지 않는다. 사용자는 "응답이 없으면
 * 마음대로 넘어가지 말고 기다려라"고 했다 — 터미널에서는 고를 때까지 기다리고(제한 시간 없음),
 * 사람이 없는 실행이면 그 자리에서 멈추고 무엇을 물으려 했는지 남긴다(2026-09-24).
 */
/** @param {string | undefined} reason */
export function noAnswerText(reason) {
  const record = "이 값을 '사용자가 확인했다'로 기록하지 마라 — 파일에 남길 때는 미확인임을 함께 적고(예: unconfirmed: true), 다음 실행에서 이 항목은 다시 물어야 한다.";
  if (reason === "no_one" || reason === "error") {
    return [
      reason === "no_one" ? "(이 실행에는 답할 사람이 없다(비대화형)." : "(질문 통로에 닿지 못해 사용자에게 묻지 못했다.",
      "기본값으로 넘어가지 마라. 요청문에 이 질문의 답이 이미 있으면 그 값을 쓰고, 없으면 여기서 작업을 멈추고",
      "무엇을 물으려 했는지와 선택지를 결과에 적어라 — 사용자가 대화형으로 다시 실행해 답하게 한다.)",
    ].join(" ");
  }
  return `(사용자가 이 질문을 건너뛰었다(Esc). 절차가 정한 기본값으로 진행하되 무엇을 가정했는지 밝혀라. ${record})`;
}

